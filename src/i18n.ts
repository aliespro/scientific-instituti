function format(str: string, vars?: Record<string, string | number>): string {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ''));
}

export function makeT(lang: Lang) {
  const dict = translations[lang] ?? translations.fa;
  return (key: string, vars?: Record<string, string | number>): string => {
    const val = dict[key] ?? translations.fa[key] ?? key;
    return format(val, vars);
  };
}

